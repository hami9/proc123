export type IconName = keyof typeof PATHS;

/**
 * An icon as an element, sized by CSS.
 *
 * The markup is a constant from the table above and never interpolates
 * anything a page or a user supplied, which is what makes `innerHTML` safe
 * here — and the only place in the app it is used.
 */
export function icon(name: IconName, className = 'icon'): SVGSVGElement {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', className);
  svg.innerHTML = PATHS[name];
  return svg;
}

export function isIconName(value: string | undefined): value is IconName {
  return value !== undefined && value in PATHS;
}
